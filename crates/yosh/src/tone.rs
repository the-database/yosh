//! MangaJaNaiConverterGui downscales grayscale pages in linear light: it
//! converts "Dot Gain 20%" → linear "Gamma 1.0" (an ICC L→L transform), resizes
//! with Catmull-Rom, then converts back. Those two transforms are pure 8-bit
//! L→L mappings, so each is exactly a 256-entry lookup table.
//!
//! These tables were extracted once from the bundled ICC profiles
//! (`Dot Gain 20%.icc`, `Custom Gray Gamma 1.0.icc`) via `PIL.ImageCms`, the
//! same library MangaJaNai uses (`run_upscale.py`), so the tone is reproduced
//! bit-exactly with no runtime ICC dependency. The dotgain20→gamma1→dotgain20
//! round trip loses up to 8 levels in the shadows — that precision loss is
//! inherent to the 8-bit ICC pipeline and matches MangaJaNai's output.

