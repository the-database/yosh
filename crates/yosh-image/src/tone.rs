/// 16-bit linear luminance → Dot Gain 20% 8-bit device, built once by inverting
/// `DOTGAIN_DECODE` (nearest device level). 64 KiB, lazily initialized.
pub fn linear_to_dotgain() -> &'static [u8; 65536] {
    static LUT: OnceLock<Box<[u8; 65536]>> = OnceLock::new();
    LUT.get_or_init(|| {
        let mut lut = Box::new([0u8; 65536]);
        let mut d = 0usize;
        for (t, slot) in lut.iter_mut().enumerate() {
            let t = t as u32;
            // Advance to the last device whose luminance is <= t.
            while d + 1 < 256 && DOTGAIN_DECODE[d + 1] as u32 <= t {
                d += 1;
            }
            // Pick the nearer of device d and d+1.
            *slot = if d + 1 < 256 {
                let lo = DOTGAIN_DECODE[d] as u32;
                let hi = DOTGAIN_DECODE[d + 1] as u32;
                if t - lo <= hi - t {
                    d as u8
                } else {
                    (d + 1) as u8
                }
            } else {
                d as u8
            };
        }
        lut
    })
}
