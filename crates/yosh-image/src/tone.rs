//! Tone curves for the high-quality grayscale downscale.
//!
//! Halftone screentones moiré badly when downscaled unless the resampling
//! happens in **true linear light** (luminance), so the black/white dots average
//! to their correct mean luminance. We:
//!   1. linearize the sRGB-encoded source to 16-bit linear luminance
//!      (`SRGB_TO_LINEAR`),
//!   2. resample in that linear space (Catmull-Rom, in `decode.rs`),
//!   3. re-encode through the **Dot Gain 20%** curve (`linear_to_dotgain`) so
//!      screentones keep the darker, inkier look (MangaJaNai's aesthetic).
//!
//! An earlier version round-tripped through a "Dot Gain 20% → Gamma 1.0" ICC
//! pair, but that profile's "Gamma 1.0" connects via L* (perceptual), not
//! luminance — only ≈gamma 1.74 — so it did NOT resample in linear light and the
//! moiré survived. These tables fix that.
//!
//! `DOTGAIN_DECODE` (Dot Gain 20% device → linear luminance) was extracted once
//! from the bundled `Dot Gain 20%.icc` via `PIL.ImageCms` (mapping the profile
//! through sRGB); `SRGB_TO_LINEAR` is the standard sRGB EOTF. `linear_to_dotgain`
//! inverts `DOTGAIN_DECODE` at runtime into a full 16-bit→8-bit table.

